"""Typeset the saved interaction record as Student/AI dialogue, without new turns."""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADERS = re.compile(
    r'^(USER(?: \(verbatim\))?|ASSISTANT|GENERATED RESULTS?|'
    r'FOLLOW-UP GENERATED RESULTS|RESULTING EDITORIAL DECISION)(?::[^\n]*)?$',
    re.MULTILINE,
)
ESCAPES = {
    '\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '$': r'\$',
    '#': r'\#', '_': r'\_', '{': r'\{', '}': r'\}',
    '~': r'\textasciitilde{}', '^': r'\textasciicircum{}',
}


def escape(text):
    return ''.join(ESCAPES.get(char, char) for char in text)


def inline(text):
    # Preserve the words; render Markdown emphasis and links as native LaTeX.
    text = html.unescape(text).replace('\xa0', ' ').replace('**', '')
    tokens = re.compile(r'\[([^\]]+)\]\(([^\s)]+)(?:\s+"[^"]*")?\)|https?://[^\s)]+')
    output, cursor = [], 0
    for token in tokens.finditer(text):
        output.append(escape(text[cursor:token.start()]))
        if token.group(1) is not None:
            output.append(r'\href{' + escape(token.group(2)) + '}{' + escape(token.group(1)) + '}')
        else:
            output.append(r'\url{' + token.group() + '}')
        cursor = token.end()
    output.append(escape(text[cursor:]))
    return ''.join(output)


def body(text):
    try:
        structured = json.loads(text)
    except (json.JSONDecodeError, ValueError):
        return '\n'.join(inline(line) + r'\par' if line.strip() else ''
                         for line in text.splitlines())
    if isinstance(structured, dict) and isinstance(structured.get('answers'), dict):
        choices = structured['answers']
        if all(isinstance(value, dict) and isinstance(value.get('answers'), list)
               for value in choices.values()):
            return '\n'.join([r'\begin{itemize}'] + [
                r'\item ' + escape(key.capitalize()) + ': ' +
                escape('; '.join(value['answers'])) for key, value in choices.items()
            ] + [r'\end{itemize}'])
    return '\n'.join([r'\begin{Verbatim}[fontsize=\small,breaklines=true,breakanywhere=true]',
                      json.dumps(structured, indent=2), r'\end{Verbatim}'])


def main():
    source = (ROOT / 'provenance/interaction_record.txt').read_text()
    matches = list(HEADERS.finditer(source))
    output = [
        '% Generated by uv run python -m tools.render_dialogue. Edit the source record.',
        r'\subsection{Recorded Student--AI Dialogue}',
        'The saved interaction record is typeset below as labeled dialogue. '
        'Markdown styling and structured responses are formatted for readability. '
        'Generated-result annotations are separate from messages. No additional '
        'historical dialogue is reconstructed. The original text remains in '
        r'\texttt{provenance/interaction\_record.txt}.',
        r'\paragraph{Record provenance.}',
        body(source[:matches[0].start()].strip()),
    ]
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(source)
        title = match.group().rstrip(':')
        title = re.sub(r'^USER\b', 'Student', title)
        title = re.sub(r'^ASSISTANT\b', 'AI', title)
        if not title.startswith(('Student', 'AI')):
            title = 'Artifact annotation: ' + title.lower()
        label = title + ':' if title in ('Student', 'AI') else title
        output.extend([r'\par\medskip\noindent\textbf{' + escape(label) + r'}\par',
                       r'\begin{quote}\small\raggedright',
                       body(source[match.end():end].strip()), r'\end{quote}'])
    destination = ROOT / 'provenance/collaboration_dialogue.tex'
    destination.write_text('\n\n'.join(output) + '\n')
    print(f'Typeset {len(matches)} recorded message/artifact blocks.')


if __name__ == '__main__':
    main()
